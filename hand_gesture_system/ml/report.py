"""
ml/report.py
------------
Plots and the paste-ready results text.  The wording is generated from the
numbers with explicit rules, so the text cannot claim more than the data shows:
differences smaller than the session-to-session spread are reported as "no clear
difference", and every class where the rules beat the model is listed.
"""

from __future__ import annotations

import os

import numpy as np

from .labels import CLASSES

ORDER = ("rules", "logreg", "forest", "mlp")
LABEL = {"rules": "Rules", "logreg": "Logistic regression", "forest": "Random forest",
         "mlp": "MLP", "mlp_norotate": "MLP, no rotation normalisation"}
WATERMARK = "SYNTHETIC DATA - pipeline check only, not a result"


def _spread(m) -> tuple[float, float]:
    v = list(m["per_session_accuracy"].values())
    return min(v), max(v)


def summary_text(res: dict, synthetic: bool, compare: str = "mlp") -> str:
    M = res["models"]
    k = len(res["sessions"])
    lines = []
    if synthetic:
        lines += [f"> **{WATERMARK}.** These sessions were generated by code, not recorded. "
                  "Do not quote any number below.", ""]
    lines += [f"Leave-one-session-out over {k} sessions, {res['n_rows']} labelled frames, one user, one camera.", ""]
    lines += ["| Classifier | Accuracy | Macro-F1 | Per-session accuracy (min to max) |", "|---|---|---|---|"]
    for n in ORDER:
        lo, hi = _spread(M[n])
        lines.append(f"| {LABEL[n]} | {M[n]['clean']['accuracy']:.3f} | {M[n]['clean']['macro_f1']:.3f} | "
                     f"{lo:.3f} to {hi:.3f} |")
    lines.append("")

    a, b = M[compare]["clean"]["macro_f1"], M["rules"]["clean"]["macro_f1"]
    lo1, hi1 = _spread(M[compare]); lo2, hi2 = _spread(M["rules"])
    spread = max(hi1 - lo1, hi2 - lo2)
    diff = a - b
    if k < 3:
        verdict = (f"With only {k} sessions the comparison is not reliable; record more sessions "
                   "before drawing a conclusion.")
    elif abs(diff) <= spread:
        verdict = (f"{LABEL[compare]} macro-F1 is {a:.3f} against {b:.3f} for the rules. That {abs(diff):.3f} gap is "
                   f"not larger than the session-to-session spread ({spread:.3f}), so there is no clear winner.")
    else:
        who = LABEL[compare] if diff > 0 else "The rules"
        verdict = (f"{who} has the higher macro-F1 ({a:.3f} {LABEL[compare]} vs {b:.3f} rules); the gap "
                   f"({abs(diff):.3f}) is larger than the session-to-session spread ({spread:.3f}).")
    lines += [verdict, ""]

    wins = [c for c in CLASSES if M["rules"]["clean"]["per_class"][c]["support"] > 0
            and M["rules"]["clean"]["per_class"][c]["f1"] > M[compare]["clean"]["per_class"][c]["f1"] + 1e-9]
    lines += ["Classes where the rules score a higher F1 than " + LABEL[compare] + ": "
              + (", ".join(wins) if wins else "none") + ".", ""]

    lines += ["Robustness (accuracy on the held-out session after transforming it; scaled hands also get "
              f"{res['jitter_px']:.0f} px of simulated landmark noise, which is a model of distance, not a real far hand):", ""]
    conds = res["conditions"]
    lines += ["| Classifier | " + " | ".join(conds) + " |", "|---|" + "---|" * len(conds)]
    for n in (*ORDER, "mlp_norotate"):
        lines.append(f"| {LABEL[n]} | " + " | ".join(f"{M[n]['robustness'][c]:.3f}" for c in conds) + " |")
    lines.append("")
    lines += [
        "Limits: one person, one camera, a handful of sessions, lighting-dependent. These numbers describe "
        "this data and say nothing about other people, cameras or rooms.", ""]
    return "\n".join(lines)


def make_plots(res: dict, out_dir: str, synthetic: bool, compare: str = "mlp") -> list[str]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    os.makedirs(out_dir, exist_ok=True)
    M = res["models"]
    colors = {"rules": "#6B727B", "logreg": "#4C78A8", "forest": "#59A14F", "mlp": "#E15759",
              "mlp_norotate": "#B07AA1"}
    paths = []

    def finish(fig, name, title):
        fig.suptitle(title, fontsize=11)
        if synthetic:
            fig.text(0.5, 0.5, WATERMARK, ha="center", va="center", rotation=20, fontsize=18,
                     color="red", alpha=0.25)
        p = os.path.join(out_dir, name)
        fig.savefig(p, dpi=150, bbox_inches="tight")
        plt.close(fig)
        paths.append(p)

    # confusion matrices: rules vs the compared model
    fig, axes = plt.subplots(1, 2, figsize=(12, 5.2))
    for ax, n in zip(axes, ("rules", compare)):
        cm = np.array(M[n]["clean"]["confusion"], dtype=float)
        norm = cm / np.maximum(cm.sum(axis=1, keepdims=True), 1)
        im = ax.imshow(norm, vmin=0, vmax=1, cmap="Blues")
        ax.set_xticks(range(len(CLASSES)), CLASSES, rotation=45, ha="right")
        ax.set_yticks(range(len(CLASSES)), CLASSES)
        for i in range(len(CLASSES)):
            for j in range(len(CLASSES)):
                if cm[i, j]:
                    ax.text(j, i, int(cm[i, j]), ha="center", va="center", fontsize=7,
                            color="white" if norm[i, j] > 0.5 else "black")
        ax.set_title(f"{LABEL[n]}  (acc {M[n]['clean']['accuracy']:.3f})")
        ax.set_xlabel("predicted"); ax.set_ylabel("true")
    fig.colorbar(im, ax=axes, fraction=0.02, label="share of true class")
    finish(fig, "confusion_matrix.png", "Held-out sessions, leave-one-session-out (cell = frames)")

    # accuracy comparison
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(12, 4.6), gridspec_kw={"width_ratios": [1, 1.6]})
    names = list(ORDER)
    a1.bar(names, [M[n]["clean"]["accuracy"] for n in names], color=[colors[n] for n in names], alpha=0.85)
    for i, n in enumerate(names):
        v = list(M[n]["per_session_accuracy"].values())
        a1.scatter([i] * len(v), v, color="black", s=14, zorder=3)
    a1.set_xticks(range(len(names)), [LABEL[n] for n in names], rotation=20, ha="right")
    a1.set_ylim(0, 1.02); a1.set_ylabel("accuracy"); a1.set_title("Clean held-out sessions\n(bar = pooled, dots = per session)")
    conds = res["conditions"]
    for n in (*ORDER, "mlp_norotate"):
        a2.plot(conds, [M[n]["robustness"][c] for c in conds], marker="o", label=LABEL[n], color=colors[n])
    a2.set_ylim(0, 1.02); a2.set_ylabel("accuracy"); a2.set_title("Robustness to rotation and (simulated) distance")
    a2.legend(fontsize=8); a2.tick_params(axis="x", rotation=30)
    finish(fig, "accuracy_comparison.png", f"{len(res['sessions'])} held-out sessions, {res['n_rows']} frames")

    # per-class F1
    fig, ax = plt.subplots(figsize=(11, 4.4))
    w = 0.2
    for k, n in enumerate(ORDER):
        ax.bar(np.arange(len(CLASSES)) + (k - 1.5) * w, [M[n]["clean"]["per_class"][c]["f1"] for c in CLASSES],
               w, label=LABEL[n], color=colors[n], alpha=0.9)
    ax.set_xticks(range(len(CLASSES)), CLASSES, rotation=30, ha="right")
    ax.set_ylim(0, 1.02); ax.set_ylabel("F1"); ax.legend(fontsize=8, ncol=4)
    finish(fig, "per_class_f1.png", "Per-class F1 on held-out sessions")
    return paths
